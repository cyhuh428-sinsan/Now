import fs from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
const box=vm.createContext({crypto:webcrypto,TextEncoder,TextDecoder,structuredClone,Uint8Array,atob,btoa});
for(const name of ['note-protection-protocol','note-protection-state','note-protection-client','note-history-state'])vm.runInContext(await fs.readFile(new URL('../vendor/'+name+'.js',import.meta.url),'utf8'),box);
const C=box.NowNoteProtectionClient,Q=box.NowNoteProtectionProtocol,H=box.NowNoteHistory;
const uid=n=>'00000000-0000-4000-8000-'+String(n).padStart(12,'0');
const scope={url:'https://synthetic.invalid',owner:'alice',local_id:'memo',device:'one',instance:uid(1)};
let ctx={...scope,enabled:true,auth:'first'},saved,failWrite=false;
const client=C.create({context:()=>ctx,stores:()=>[]});
assert.equal(typeof client.saveJournal,'function','protected drafts need the existing account journal CAS path');
const note={id:7,owner_id:'alice',local_id:'memo',device_id:'one',note_type:'tree',title:'Title',content:'JOURNAL-PRIVATE-DRAFT',parent_local_id:null,level:1,tags:null,source:null,deleted_at:null,created_at:'2026-10-30T00:00:00.000001Z',updated_at:'2026-10-30T00:00:00.000002Z',client_updated_at:null};
const value={raw:structuredClone(note),draft:structuredClone(note),base:{inventory_revision_ids:[]},revisions:[],outbox:[],receipts:[]};
const old={protection_record:{schema_version:1,scope,operation_id:uid(2),ciphertext:await Q.encryptContent(JSON.stringify({schema_version:1,scope,operation_id:uid(2),value}),'password')}};
const initial={schema_version:1,contexts:{[H.key(scope)]:{notes:{memo:old,other:{raw:{content:'PRESERVE'},draft:{content:'PRESERVE'},base:{inventory_revision_ids:[]},revisions:[],outbox:[],receipts:[]}}}}};
const journal=H.create({initial,context:()=>ctx,request:async()=>{throw Error('no_network');},write:async raw=>{if(failWrite)throw Error('CAS_conflict');assert.equal(JSON.stringify(raw).includes(note.content),false);saved=structuredClone(raw);}});
const record=await client.saveJournal(scope,old,value,'password',uid(3),journal);
const bucket=()=>journal.export().contexts[H.key(scope)].notes;
assert.equal(bucket().memo.protection_record.operation_id,uid(3));assert.equal(bucket().other.raw.content,'PRESERVE');
assert.equal((await client.openArchive(scope,record,'password')).draft.content,note.content);
assert.equal(JSON.stringify(saved).includes(note.content),false);
await assert.rejects(client.saveJournal(scope,old,value,'password',uid(4),journal),/copy_changed/);
failWrite=true;
await assert.rejects(client.saveJournal(scope,record,value,'password',uid(4),journal),/CAS_conflict/);
assert.deepEqual(bucket().memo,record);
failWrite=false;
const foreign=structuredClone(value);foreign.draft.owner_id='bob';
await assert.rejects(client.saveJournal(scope,record,foreign,'password',uid(4),journal),/scope/);
ctx={...ctx,owner:'bob',auth:'bob'};
await assert.rejects(client.saveJournal(scope,record,value,'password',uid(4),journal),/confirmation_changed|scope/);
assert.equal(saved.contexts[H.key(scope)].notes.other.raw.content,'PRESERVE');
ctx={...scope,enabled:true,auth:'fresh'};
const input=structuredClone(value),freezing=client.saveJournal(scope,record,input,'password',uid(5),journal);
input.draft.content='MUTATED-AFTER-CALL';
const frozen=await freezing;
assert.equal((await client.openArchive(scope,frozen,'password')).draft.content,note.content);
box.NowNoteProtectionProtocol={...Q,encryptContent:async(...args)=>{const raw=await Q.encryptContent(...args);ctx.auth='changed-during-encryption';return raw;}};
await assert.rejects(client.saveJournal(scope,frozen,value,'password',uid(6),journal),/confirmation_changed/);
assert.deepEqual(bucket().memo,frozen);
box.NowNoteProtectionProtocol=Q;
console.log('Protected journal CAS: ciphertext-only, original entry CAS, rollback, account/target scope and other-note preservation PASS (synthetic storage)');
