import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
import { setTimeout as delay } from 'node:timers/promises';
import { launchApp, evaluate, stopProcess } from '../../desktop/scripts/check-desktop-storage.mjs';
const base = 'D:/tmp/now-240-stage-e3';
const accounts = JSON.parse(await fs.readFile(base + '/synthetic-accounts.json', 'utf8'));
const profile = await fs.mkdtemp(base + '/electron-');
let app;
const until = async expression => { for (let i = 0; i < 150; i++) { if (await evaluate(app.page, expression)) return; await delay(50); } throw Error('timeout: ' + expression); };
const run = expression => evaluate(app.page, expression);
const results = [];
try {
  app = await launchApp(profile);
  await until('Boolean(noteHistory && noteHistoryUI)');
  await run(`state.settings.server = normalizeServerSettings({ ...state.settings.server, mode:'server', url:'http://127.0.0.1:8750', ownerId:'qa_history_alice', deviceId:'history-electron', userToken:${JSON.stringify(accounts.qa_history_alice.token)}, autoSync:false }); persistSettings();`);
  await run('loadServerSharedNotes({replace:true})');
  const id = await run(String.raw`(() => { const node=createNode('E3 실제 저장', '첫 본문\n', null, 1); node.shared=true; state.data.tree.push(node); state.selectedTreeId=node.id; persist(); render(); return node.id; })()`);
  await run('noteHistoryFlush()');
  const first = await run(`noteHistory.view(${JSON.stringify(id)})`);
  assert.equal(first.outbox.length, 0, JSON.stringify(first));
  assert.equal(first.base.head_version, 1);
  assert.equal(await run('buildServerSyncNotes(state.settings.server).length'), 0, 'managed note must not upload v1');
  results.push('actual HTTP initial save + v1 exclusion');
  await run(String.raw`elements.treeContent.value='두 번째 본문\n'; flushTreeContentInput();`);
  await run('noteHistoryFlush()');
  assert.equal(await run(`noteHistory.view(${JSON.stringify(id)}).base.head_version`), 2);
  await run(`noteHistoryUI.open(${JSON.stringify(id)})`);
  assert.equal(await run('document.querySelector("#noteHistoryDialog").open'), true);
  assert.ok(await run('document.querySelectorAll("#noteHistoryDialog [name=after] option").length') >= 3);
  const shot = await app.page.send('Page.captureScreenshot', { format: 'png' });
  await fs.writeFile(base + '/electron-history.png', Buffer.from(shot.data, 'base64'));
  await run('noteHistoryUI.close()');
  results.push('actual history UI + server reason list');
  await run(`noteHistoryUI.open(${JSON.stringify(id)})`);
  await run(`(() => { const select=document.querySelector('#noteHistoryDialog [name=after]'); select.value=JSON.stringify({kind:'note_revision',id:${JSON.stringify(first.base.head_revision_id)}});select.dispatchEvent(new Event('change',{bubbles:true}));document.querySelector('#noteHistoryDialog [data-action=restore]').click(); })()`);
  await until('Boolean(document.querySelector("#noteHistoryDialog [role=alertdialog]"))');
  await run('document.querySelector("#noteHistoryDialog [role=alertdialog] button:last-child").click()');
  await until('document.querySelector("#noteHistoryDialog .history-status").textContent.includes("복원 완료")');
  const restored = await run(`noteHistory.view(${JSON.stringify(id)})`);
  assert.equal(restored.draft.content, first.draft.content);
  assert.equal(restored.dirty, false);
  await run('noteHistoryUI.close(); noteHistoryFlush()');
  const afterFlush = await run(`noteHistoryRequest(noteHistoryContext(),'current','GET',{local_id:${JSON.stringify(id)}})`);
  assert.equal(afterFlush.snapshot.note.content, first.draft.content, 'flush after restore must not resend the pre-restore draft');
  assert.equal(afterFlush.head_revision_id, restored.base.head_revision_id);
  results.push('actual UI restore + subsequent flush keeps restored server head');
  await run(`elements.treeContent.value=${JSON.stringify('두 번째 본문\n')}; flushTreeContentInput();`);
  await run('noteHistoryFlush()');
  assert.equal(await run(`noteHistory.view(${JSON.stringify(id)}).dirty`), false);
  assert.equal((await run(`noteHistoryRequest(noteHistoryContext(),'current','GET',{local_id:${JSON.stringify(id)}})`)).snapshot.note.content, '두 번째 본문\n');
  results.push('actual edit back to pre-restore value creates a new server revision');
  await run(`noteHistoryUI.open(${JSON.stringify(id)})`);
  await run(`(() => {
    const fetcher=globalThis.fetch;globalThis.__e3FetchRestore=fetcher;
    globalThis.fetch=(...args)=>String(args[0]).includes('/api/v2/notes/restore')&&args[1]?.method==='POST'?new Promise(resolve=>{globalThis.__e3ReleaseRestore=()=>resolve(fetcher(...args));}):fetcher(...args);
    const select=document.querySelector('#noteHistoryDialog [name=after]');select.value=JSON.stringify({kind:'note_revision',id:${JSON.stringify(first.base.head_revision_id)}});select.dispatchEvent(new Event('change',{bubbles:true}));document.querySelector('#noteHistoryDialog [data-action=restore]').click();
  })()`);
  await until('Boolean(document.querySelector("#noteHistoryDialog [role=alertdialog]"))');
  await run('document.querySelector("#noteHistoryDialog [role=alertdialog] button:last-child").click()');
  await until('typeof globalThis.__e3ReleaseRestore === "function"');
  await run(`elements.treeContent.value=${JSON.stringify('restore in-flight draft')};flushTreeContentInput();noteHistoryCaptureChain`);
  await run('globalThis.__e3ReleaseRestore();globalThis.fetch=globalThis.__e3FetchRestore;delete globalThis.__e3FetchRestore;delete globalThis.__e3ReleaseRestore;');
  await until('document.querySelector("#noteHistoryDialog .history-status").textContent.includes("복원 완료")');
  assert.equal(await run(`noteHistory.view(${JSON.stringify(id)}).draft.content`), 'restore in-flight draft');
  assert.equal(await run(`findTreeNode(state.data.tree,${JSON.stringify(id)}).content`), 'restore in-flight draft', 'restore UI must not project over a later edit');
  results.push('actual restore in-flight edit retained in journal and editor');
  await run('noteHistoryUI.close()');
  await run(`elements.treeContent.value=${JSON.stringify('두 번째 본문\n')};flushTreeContentInput();noteHistoryCaptureChain`);
  await run('noteHistoryFlush()');
  app.client.close(); stopProcess(app.app); app = null; await delay(500);
  app = await launchApp(profile);
  await until('Boolean(noteHistory && noteHistoryUI)');
  assert.equal(await run(`noteHistory.view(${JSON.stringify(id)}).draft.content`), '두 번째 본문\n');
  assert.equal(await run(`findTreeNode(state.data.tree, ${JSON.stringify(id)}).content`), '두 번째 본문\n');
  results.push('actual Electron restart + journal projection');
  await run(`state.selectedTreeId=${JSON.stringify(id)};render();elements.treeContent.value='committed before IME';flushTreeContentInput();noteHistoryCaptureChain`);
  const beforeIme = await run(`noteHistory.view(${JSON.stringify(id)}).revisions.length`);
  await run(`elements.treeContent.dispatchEvent(new CompositionEvent('compositionstart',{bubbles:true}));noteHistoryFlush()`);
  assert.equal(await run(`noteHistory.view(${JSON.stringify(id)}).revisions.length`),beforeIme,'IME composition must defer journal sealing');
  await run(`elements.treeContent.dispatchEvent(new CompositionEvent('compositionend',{bubbles:true}));elements.treeContent.value=${JSON.stringify('두 번째 본문\n')};flushTreeContentInput();noteHistoryFlush()`);
  results.push('actual IME composition defers sealing without discarding durable draft');
  const exported = await run('noteHistory.export()');
  assert.equal(JSON.stringify(exported).includes(accounts.qa_history_alice.token), false);
  assert.equal(JSON.stringify(exported).includes('session_token'), false);
  results.push('no synthetic token in journal');
  await app.page.send('Network.enable');
  await app.page.send('Network.emulateNetworkConditions', { offline: true, latency: 0, downloadThroughput: -1, uploadThroughput: -1 });
  await run(`state.selectedTreeId=${JSON.stringify(id)}; render();`);
  await run(String.raw`elements.treeContent.value='오프라인 재시작 보존\n'; flushTreeContentInput();`);
  await run('noteHistoryFlush()');
  assert.ok(await run(`noteHistory.view(${JSON.stringify(id)}).outbox.length`) > 0);
  app.client.close(); stopProcess(app.app); app = null; await delay(500);
  app = await launchApp(profile); await until('Boolean(noteHistory && noteHistoryUI)');
  assert.equal(await run(`noteHistory.view(${JSON.stringify(id)}).draft.content`), '오프라인 재시작 보존\n');
  await run('noteHistoryFlush()');
  assert.equal(await run(`noteHistory.view(${JSON.stringify(id)}).outbox.length`), 0);
  results.push('actual offline edit + cold restart + branch import and HTTP reconnect');
  const ipcGuard = await run(`(async()=>{const saved=await window.nownoteDesktop.storage.read('nownote.history.v1');try {await window.nownoteDesktop.storage.write('nownote.history.v1',{schema_version:1,contexts:{}},{expectedValue:null});return false;}catch {return JSON.stringify(await window.nownoteDesktop.storage.read('nownote.history.v1'))===JSON.stringify(saved);}})()`);
  assert.equal(ipcGuard, true); results.push('actual journal IPC stale CAS preserves saved outbox/history');
  const schemaGuard = await run(`(async()=>{
    const original=noteHistory.export(), disk=await window.nownoteDesktop.storage.read(NOTE_HISTORY_KEY), fetcher=globalThis.fetch;
    let writes=0;globalThis.fetch=(...args)=>{if((String(args[0]).includes('/api/v1/')||String(args[0]).includes('/api/v2/'))&&['POST','PUT'].includes(args[1]?.method))writes++;return fetcher(...args);};
    try {for(const value of [{schema_version:99,opaque:'preserve'},{schema_version:1,contexts:{bad:{notes:[]}}}]){
      noteHistory.hydrate(value);await syncWebNotesToServer(undefined,{skipFormSave:true});
      if(!noteHistory.status().unsupported||buildServerSyncNotes(state.settings.server).length||JSON.stringify(await window.nownoteDesktop.storage.read(NOTE_HISTORY_KEY))!==JSON.stringify(disk))return false;
    }return writes===0;}finally{globalThis.fetch=fetcher;noteHistory.hydrate(original);}
  })()`);
  assert.equal(schemaGuard,true);results.push('actual Electron unknown/malformed journal blocks v1/v2 writes and preserves disk');
  assert.equal(await run(`historyProtectionTransitionBlocked(findTreeNode(state.data.tree,${JSON.stringify(id)}))`),true);
  await run(`(() => {const n=findTreeNode(state.data.tree,${JSON.stringify(id)});n.shared=false;n.unsharedAt=new Date().toISOString();markTreeNodeChanged(n);persist();})()`);
  await run('noteHistoryFlush()');
  const unshare = await run(`(async()=>({current:await noteHistoryRequest(noteHistoryContext(),'current','GET',{local_id:${JSON.stringify(id)}}),local:findTreeNode(state.data.tree,${JSON.stringify(id)})}))()`);
  assert.ok(unshare.current.snapshot.note.deleted_at, 'shared server copy must become a tombstone on unshare');
  assert.equal(unshare.local.content, '오프라인 재시작 보존\n', 'unshare must preserve local body');
  results.push('actual unshare tombstone keeps local private body');
  await fs.writeFile(base + '/electron-history-result.json', JSON.stringify({ results }, null, 2));
  console.log(results.join('\n'));
} finally {
  if (app) { app.client.close(); stopProcess(app.app); }
  await delay(500);
  await fs.rm(profile, { recursive: true, force: true });
}
