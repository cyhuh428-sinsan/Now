import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
import {webcrypto} from 'node:crypto';
const box={crypto:webcrypto,TextEncoder};
vm.createContext(box);
vm.runInContext(await fs.readFile(new URL('../vendor/marked.umd.js',import.meta.url),'utf8'),box);
let source='';
try{source=await fs.readFile(new URL('../vendor/note-blocks.js',import.meta.url),'utf8');}catch{}
vm.runInContext(source,box);
assert.ok(box.NowNoteBlocks,'Stable source blocks must exist');
const B=box.NowNoteBlocks;
const id='11111111-1111-4111-8111-111111111111',other='22222222-2222-4222-8222-222222222222';
const original='First **body**\r\n\r\nSecond paragraph\r\n';
const anchored=B.anchor(original,2,6);
assert.match(anchored.blockId,/^[0-9a-f-]{36}$/);
assert.ok(anchored.source.startsWith('First **body**\r\n\r\n^'+anchored.blockId));
assert.ok(anchored.source.endsWith('\r\n\r\nSecond paragraph\r\n'));
const block=B.index(anchored.source).find(row=>row.id===anchored.blockId);
assert.equal(block.content,'First **body**');
assert.equal(B.anchor(anchored.source,2,6).source,anchored.source,'Repeated copy keeps stable ID');
assert.ok(B.anchor('Caret at block end',18).blockId,'A caret at the end of a block must work');
assert.throws(()=>B.anchor(original,0,original.length),/한 블록/);
const code='\`\`\`text\ninside ^'+id+'\n\`\`\`\n\n<div>fake ^'+id+'</div>\n';
assert.equal(B.index(code).filter(row=>row.id).length,0,'Code/HTML cannot create fake anchors');
const codeAnchor=B.anchor(code,5,10);
assert.equal(B.index(codeAnchor.source).find(row=>row.id===codeAnchor.blockId).type,'code');
assert.ok(B.stripAnchors(codeAnchor.source).includes('inside ^'+id),'Code literal marker stays visible');
const inline='Original\nline ^'+id+'\n';
assert.equal(B.index(inline).find(row=>row.id===id).content,'Original\nline');
assert.equal(B.stripAnchors(inline),'Original\nline \n');
const duplicate='One ^'+id+'\n\nTwo ^'+id;
const ref=B.reference('계정/한글','note/#?%',id);
assert.deepEqual(JSON.parse(JSON.stringify(B.parse(ref))),{owner:'계정/한글',localId:'note/#?%',blockId:id});
assert.equal(B.parse('![[nownote:%GG/id#^'+id+']]'),null);
const notes={n:{owner:'me',content:'Original ^'+id,title:'Source',status:'ok'}};
const ctx={owner:'me',lookup:local=>notes[local]};
const target=B.reference('me','n',id);
let resolved=B.resolve(target,ctx);
assert.equal(resolved.status,'ok');assert.equal(resolved.content,'Original');
notes.n.content='Moved elsewhere\n\nChanged **body** ^'+id;
assert.equal(B.resolve(target,ctx).content,'Changed **body**','Move/edit keeps source identity');
notes.n.content='Replacement without marker';
assert.equal(B.resolve(target,ctx).status,'missing_block','Missing anchor is not guessed');
notes.n.content=duplicate;
assert.equal(B.resolve(target,ctx).status,'ambiguous_block');
notes.n.content='Original ^'+id;
for(const status of ['locked','unavailable','deleted']){
  notes.n.status=status;
  const result=B.resolve(target,ctx);
  assert.equal(result.status,status);assert.equal(result.title,undefined);assert.equal(result.content,undefined);
}
notes.n.status='ok';notes.n.owner='other';
assert.equal(B.resolve(target,ctx).status,'unavailable');
notes.n.owner='me';
let lookups=0;
assert.equal(B.resolve(target,{owner:'other',lookup:()=>{lookups++;}}).status,'unavailable');
assert.equal(lookups,0,'Cross-account lookup is forbidden');
resolved=B.resolve(target,ctx);
assert.equal(B.resolve(target,ctx,resolved.next).status,'cycle');
const next=B.reference('me','second',other);
notes.second={owner:'me',content:'Second ^'+other,status:'ok'};
const limited=B.resolve(target,ctx,{trail:[],budget:{count:0,bytes:0,maxDepth:1,maxBlocks:10,maxBytes:1024}});
assert.equal(B.resolve(next,ctx,limited.next).status,'depth_limit');
assert.equal(B.resolve(target,ctx,{trail:[],budget:{count:0,bytes:0,maxDepth:5,maxBlocks:0,maxBytes:1024}}).status,'budget_limit');
assert.equal(B.resolve(target,ctx,{trail:[],budget:{count:0,bytes:0,maxDepth:5,maxBlocks:10,maxBytes:1}}).status,'budget_limit');
console.log('Source blocks: stable IDs, raw CRLF, code/HTML, scope, duplicate/missing, cycle and budgets PASS');
