const box={crypto:webcrypto,structuredClone,TextEncoder,TextDecoder,Uint8Array,atob,btoa};
for(const name of ['note-protection-protocol','note-protection-state','note-history-state'])
  vm.runInNewContext(await fs.readFile(new URL('../vendor/'+name+'.js',import.meta.url),'utf8'),box);
const H=box.NowNoteHistory,ctx={url:'https://example.invalid',owner:'vault-fixture',device:'fixture',enabled:true,online:true,auth:'synthetic'};
assert.equal(typeof H.prepareExternalEdit,'function');
const note={owner_id:ctx.owner,local_id:'t',note_type:'tree',title:'Topic',content:'before',parent_local_id:null,level:1,tags:'',source:'web-tree',deleted_at:null};
const base={head_version:1,head_revision_id:'fixture-revision',inventory_revision_ids:['fixture-revision'],crypto_epoch:0,replica_count:1,snapshot:{schema_version:1,note}};
const journal=H.create({context:()=>ctx,write:async()=>{},request:async()=>{throw Error('external_network_forbidden');}});
await journal.track(note,base);
await journal.edit({...note,content:'unsent before import'});
const initial=journal.export(), original=JSON.stringify(initial);
const patch=await H.prepareExternalEdit(initial,ctx,{...note,content:'from Obsidian'});
assert.equal(JSON.stringify(initial),original);
assert.equal(patch.expected.draft.content,'unsent before import');
assert.equal(patch.next.draft.content,'from Obsidian');
assert.equal(patch.next.raw.content,'before');
assert.equal(patch.next.dirty,true);
assert.equal(patch.next.revisions.find(r=>r.reason==='before_external_import').snapshot.note.content,'unsent before import');
assert.equal(patch.next.outbox[0].body.note.content,'unsent before import');
assert.equal(patch.next.revisions.at(-1).reason,'external_import');
assert.equal(patch.next.revisions.at(-1).snapshot.note.content,'from Obsidian');
assert.equal(JSON.stringify(patch).includes(ctx.auth),false);
assert.deepEqual(patch.next.base,initial.contexts[H.key(ctx)].notes.t.base);
assert.equal(JSON.stringify(patch.next.receipts),JSON.stringify(initial.contexts[H.key(ctx)].notes.t.receipts));
