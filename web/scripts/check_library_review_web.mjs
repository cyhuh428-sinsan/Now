import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
const base='D:/tmp/now-240-stage-d';
const accounts=JSON.parse(await fs.readFile(`${base}/synthetic-accounts.json`,'utf8'));
const task=await taskSpace('NowNote Stage D review'),page=task.page('p1');
const origin=`http://nownote-review-${Date.now()}.localhost:8750`;
await page.goto(origin);
await page.fill('#webLoginOwnerInput','qa_library_alice');
await page.fill('#webLoginPasswordInput','StageD-synthetic-only-42!');
await page.click('#webLoginSubmitBtn');
await page.waitForFunction(()=>Boolean(libraryStore&&libraryContext().enabled&&document.querySelector('#libraryBtn')?.offsetParent));
assert.equal(await page.evaluate(()=>isHostedWebClient()),true);
await page.click('#libraryBtn');
await page.click('#libraryDetail [data-action="clone"]');
await page.waitForFunction(()=>document.querySelector('#libraryList [aria-current="true"]')?.dataset.id&&!document.querySelector('#libraryList [aria-current="true"]').dataset.id.startsWith('builtin:'));
const id=await page.evaluate(()=>document.querySelector('#libraryList [aria-current="true"]').dataset.id);
await page.waitForFunction(id=>libraryStore.list('templates').some(r=>r.id===id&&r.version>0&&!r.pending),id);
await page.fill('#libraryForm [name="content"]','Web typed from shown version');
const list=async()=>{
  const r=await fetch('http://127.0.0.1:8750/api/v1/templates?owner_id=qa_library_alice&include_deleted=true',{headers:{'X-Now-Web-Session':accounts.qa_library_alice.session}});
  assert.equal(r.status,200);return(await r.json()).items;
};
let row=(await list()).find(r=>r.id===id);
const viewed=row.version;
const peer=async text=>{
  const r=await fetch(`http://127.0.0.1:8750/api/v1/templates/${id}`,{method:'PUT',headers:{'Content-Type':'application/json','X-Now-Web-Session':accounts.qa_library_alice.session},body:JSON.stringify({owner_id:'qa_library_alice',schema_version:1,base_version:row.version,mutation_id:crypto.randomUUID(),payload:{...row.payload,content_template:text}})});
  const result=await r.json();assert.equal(r.status,200,JSON.stringify(result));row=result.resource;
};
await peer('Web peer update while editing');
await page.click('#libraryDialog [data-action="sync"]');
await page.waitForFunction(({id,version})=>libraryStore.status().resources['templates/'+id]?.version===version,{id,version:row.version});
assert.equal(await page.evaluate(()=>document.querySelector('#libraryForm [name="content"]').value),'Web typed from shown version');
await page.click('#libraryDetail [data-action="save"]');
await page.waitForSelector('.library-conflict');
assert.equal(await page.evaluate(id=>libraryStore.status().outbox.find(o=>o.id===id).body.base_version,id),viewed);
assert.equal((await list()).find(r=>r.id===id).payload.content_template,'Web peer update while editing');
await peer('Web peer third version after comparison');
await page.click('#libraryDialog [data-action="sync"]');
await page.waitForFunction(({id,version})=>libraryStore.status().resources['templates/'+id]?.version===version,{id,version:row.version});
await page.click('.library-conflict button >> nth=0');
await page.waitForFunction(()=>document.querySelector('#libraryStatus').textContent.includes('다시 비교'));
assert.equal((await list()).find(r=>r.id===id).payload.content_template,'Web peer third version after comparison');
await page.screenshot({path:`${base}/review-web-conflict.png`});
await page.click('.library-conflict button >> nth=0');
await page.waitForFunction(id=>libraryStore.list('templates').some(r=>r.id===id&&!r.pending&&r.payload.content_template==='Web typed from shown version'),id);
await page.click(`#libraryList [data-id="${id}"]`);
row=(await list()).find(r=>r.id===id);const deleteViewed=row.version;
await peer('Web peer before delete');
await page.evaluate(()=>libraryStore.sync());
await page.click('#libraryDetail [data-action="delete"]');
await page.click('.library-confirm button >> nth=1');
await page.waitForSelector('.library-conflict');
assert.equal(await page.evaluate(id=>libraryStore.status().outbox.find(o=>o.id===id).body.base_version,id),deleteViewed);
assert.equal((await list()).find(r=>r.id===id).deleted_at,null);
await fs.writeFile(`${base}/review-web-http.json`,JSON.stringify({hosted:true,actualHTTP:true,dirtyFormPreserved:true,displayedVersionCAS:true,conflictRemoteVersionBound:true,thirdVersionRequiresReselection:true,staleDeleteBlocked:true},null,2));
await page.evaluate(()=>{for(const k of Object.keys(localStorage).filter(k=>k.startsWith('nownote.')))localStorage.removeItem(k);for(const k of Object.keys(sessionStorage).filter(k=>k.startsWith('nownote.')))sessionStorage.removeItem(k);});
await page.cdp('Storage.clearDataForOrigin',{origin,storageTypes:'cache_storage,service_workers'});
await task.finish({keep:[]});
console.log('Stage D review Web: actual hosted login/HTTP/dirty form CAS/conflict reselection/stale delete PASS');
