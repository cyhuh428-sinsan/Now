import assert from 'node:assert/strict';
import { promises as fs } from 'node:fs';
const task = await taskSpace('NowNote Stage D');
const page = task.page(JSON.parse(await fs.readFile('D:/tmp/now-240-stage-d/hosted-page.json', 'utf8')).page);
await page.fill('#webLoginOwnerInput', 'qa_library_alice');
await page.fill('#webLoginPasswordInput', 'StageD-synthetic-only-42!');
await page.click('#webLoginSubmitBtn');
await page.waitForFunction(() => !document.querySelector('#webLoginView')?.classList.contains('hidden') ? Boolean(state.settings.server.webSessionToken && document.querySelector('#libraryBtn')?.offsetParent) : true);
await page.click('#libraryBtn');
await page.click('#libraryDetail [data-action="clone"]');
await page.fill('#libraryForm [name="name"]', 'HTTP 템플릿');
await page.fill('#libraryForm [name="content"]', '# {{title}}\n합성 HTTP 왕복 {{date}}');
await page.click('#libraryDetail [data-action="save"]');
await page.waitForFunction(() => libraryStore.list('templates').some(r => r.payload.name === 'HTTP 템플릿' && r.version > 0 && !r.pending));
const seed = await page.evaluate(() => ({ template: libraryStore.list('templates').find(r => r.payload.name === 'HTTP 템플릿'), hosted: isHostedWebClient() }));
assert.equal(seed.hosted, true);
await page.click('#libraryDialog [data-kind="saved-queries"]');
await page.click('#libraryDialog [data-action="new"]');
await page.fill('#libraryForm [name="name"]', 'HTTP 저장조건');
await page.fill('#libraryForm [name="text"]', 'HTTP');
await page.click('#libraryDetail [data-action="save"]');
await page.waitForFunction(() => libraryStore.list('saved-queries').some(r => r.payload.name === 'HTTP 저장조건' && r.version > 0 && !r.pending));
seed.query = await page.evaluate(() => libraryStore.list('saved-queries').find(r => r.payload.name === 'HTTP 저장조건'));
await page.cdp('Network.enable');
await page.cdp('Network.emulateNetworkConditions', { offline: true, latency: 0, downloadThroughput: -1, uploadThroughput: -1 });
await page.fill('#libraryForm [name="text"]', '오프라인 수정');
await page.click('#libraryDetail [data-action="save"]');
await page.waitForFunction(() => libraryStore.status().outbox.some(o => o.body.payload?.filter?.text === '오프라인 수정'));
assert.ok(await page.evaluate(() => JSON.parse(localStorage.getItem('nownote.library.v1')).contexts[NowLibrary.key(libraryContext())].outbox.length));
await page.cdp('Network.emulateNetworkConditions', { offline: false, latency: 0, downloadThroughput: -1, uploadThroughput: -1 });
await page.reload();
await page.waitForFunction(() => libraryStore?.list('saved-queries').some(r => r.payload.filter.text === '오프라인 수정' && r.version >= 2 && !r.pending));
await page.click('#libraryBtn');
await page.click('#libraryDialog [data-kind="saved-queries"]');
await page.click('#libraryList .library-item');
const snapshot = await page.evaluate(() => { const snap = createRecoverySnapshot('stage-d-qa'); return normalizeRecoverySnapshot(snap); });
assert.ok(snapshot.library.contexts);
const downloadPromise = page.waitForEvent('download');
await page.evaluate(() => downloadCurrentBackup('stage-d-synthetic'));
const download = await downloadPromise;
await download.saveAs('D:/tmp/now-240-stage-d/full-backup.json');
const backup = JSON.parse(await fs.readFile('D:/tmp/now-240-stage-d/full-backup.json', 'utf8'));
assert.equal(backup.version, 3);
assert.ok(backup.library.contexts);
await fs.writeFile('D:/tmp/now-240-stage-d/web-http-seed.json', JSON.stringify(seed, null, 2));
console.log('Stage D hosted Web: real login/template+query HTTP/offline-persist/reload-reconnect/full backup/snapshot PASS', { templateId: seed.template.id, queryId: seed.query.id });
